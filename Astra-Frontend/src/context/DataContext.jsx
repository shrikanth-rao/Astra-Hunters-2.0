export function DataProvider({ children }) {
  const [users, setUsers] = useState(initialUsers);
  const [currentUser, setCurrentUser] = useState(null);
  const [pendingAnalysis, setPendingAnalysis] = useState(null);
  // Store other shared application data here
  const [analysisResults, setAnalysisResults] = useState([]);
  const [history, setHistory] = useState([]);
  const [progressByUser, setProgressByUser] = useState(initialProgress);

  const getUserProgress = (gmail) => {
    return progressByUser[gmail] || [];
  };

  const addSpeechResult = (gmail, speech) => {
    setProgressByUser((prev) => ({
      ...prev,
      [gmail]: [
        ...(prev[gmail] || []),
        {
          id: Date.now(),
          ...speech,
        },
      ],
    }));
  };

  const value = {
  users,
  setUsers,
  currentUser,
  setCurrentUser,

  pendingAnalysis,
  setPendingAnalysis,

  analysisResults,
  setAnalysisResults,
  history,
  setHistory,
  progressByUser,
  getUserProgress,
  addSpeechResult,
};

  return (
    <DataContext.Provider value={value}>
      {children}
    </DataContext.Provider>
  );
}

export function useData() {
  return useContext(DataContext);
}